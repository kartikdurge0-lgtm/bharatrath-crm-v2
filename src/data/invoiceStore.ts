const STORAGE_KEY = "bharatrath_crm_invoices";

/* =========================================================
   HELPERS
========================================================= */

function generateId(prefix: string): string {
  return `${prefix}-${Date.now()}-${Math.random()
    .toString(36)
    .substring(2, 8)}`;
}

function roundMoney(value: number): number {
  return Math.round((value + Number.EPSILON) * 100) / 100;
}

function invoiceRecordName(invoice: Invoice): string {
  return invoice.invoiceNumber || invoice.id;
}

/* =========================================================
   INVOICE NUMBER TYPES
========================================================= */

export type InvoiceNumberPrefix = "BDP" | "QTN" | "REN";

/* =========================================================
   INVOICE NUMBER PREFIX
========================================================= */

/*
 * Invoice numbering policy:
 *
 * Normal invoice:
 * BDP-002-2026-001
 *
 * Invoice created from quotation:
 * BDP-002-2026-002
 *
 * Renewal invoice:
 * REN-002-2026-001
 *
 * IMPORTANT:
 *
 * A quotation number is only a reference.
 * It must NOT change the invoice prefix.
 *
 * Example:
 *
 * Quotation:
 * QUO-009
 *
 * Invoice:
 * BDP-002-2026-001
 *
 * This keeps quotation numbering and invoice numbering
 * completely separate.
 */

function getInvoicePrefix(input: CreateInvoiceInput): InvoiceNumberPrefix {
  if (input.renewalId || input.renewalReference) {
    return "REN";
  }

  return "BDP";
}

/* =========================================================
   CLIENT SERIAL
========================================================= */

/*
 * CRM Client IDs:
 *
 * CL-001
 * CL-002
 * CL-003
 *
 * Invoice uses:
 *
 * 001
 * 002
 * 003
 */

function getClientSerial(clientId: string): string {
  const value = String(clientId || "").trim();

  const match = value.match(/(\d+)$/);

  if (!match) {
    return "000";
  }

  return String(Number(match[1])).padStart(3, "0");
}

/* =========================================================
   GET ALL INVOICES
========================================================= */

export function getInvoices(): Invoice[] {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);

    if (!stored) {
      return [];
    }

    const parsed: unknown = JSON.parse(stored);

    if (!Array.isArray(parsed)) {
      return [];
    }

    return (parsed as Invoice[]).map((invoice) => ({
      ...invoice,

      payments: Array.isArray(invoice.payments) ? invoice.payments : [],
    }));
  } catch (error) {
    console.error("Failed to load invoices:", error);

    return [];
  }
}

/* =========================================================
   SAVE INVOICES
========================================================= */

export function saveInvoices(invoices: Invoice[]): void {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(invoices));
}

/* =========================================================
   GENERATE INVOICE NUMBER
========================================================= */

/*
 * Final format:
 *
 * PREFIX-CLIENT-YEAR-SERIAL
 *
 * Examples:
 *
 * BDP-002-2026-001
 * BDP-002-2026-002
 * REN-002-2026-001
 */

export function generateInvoiceNumber(
  clientId: string,
  prefix: InvoiceNumberPrefix = "BDP",
  invoiceDate?: string,
): string {
  const invoices = getInvoices();

  const date = invoiceDate ? new Date(invoiceDate) : new Date();

  const year = date.getFullYear();

  const clientSerial = getClientSerial(clientId);

  const numberPrefix = `${prefix}-${clientSerial}-${year}-`;

  let highestSerial = 0;

  invoices.forEach((invoice) => {
    const invoiceNumber = String(invoice.invoiceNumber || "").trim();

    if (!invoiceNumber.startsWith(numberPrefix)) {
      return;
    }

    const parts = invoiceNumber.split("-");

    if (parts.length !== 4) {
      return;
    }

    const serial = Number(parts[3]);

    if (!Number.isNaN(serial)) {
      highestSerial = Math.max(highestSerial, serial);
    }
  });

  return `${numberPrefix}${String(highestSerial + 1).padStart(3, "0")}`;
}

