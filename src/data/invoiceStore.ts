/* =========================================================
   PAYMENT SUMMARY
========================================================= */

export interface InvoicePaymentSummary {
  totalPaid: number;
  balance: number;
  isPaid: boolean;
}

export function getInvoicePaymentSummary(
  invoice: Invoice,
): InvoicePaymentSummary {
  const activePayments = Array.isArray(invoice.payments)
    ? invoice.payments.filter((payment) => payment.status !== "Cancelled")
    : [];

  const totalPaid = roundMoney(
    activePayments.reduce(
      (total, payment) => total + Number(payment.amountPaid || 0),
      0,
    ),
  );

  const balance = Math.max(0, roundMoney(invoice.grandTotal - totalPaid));

  return {
    totalPaid,

    balance,

    isPaid: balance <= 0,
  };
}

/* =========================================================
   SEARCH INVOICES
========================================================= */

export function searchInvoices(
  searchTerm: string,
  status: InvoiceStatus | "All" = "All",
): Invoice[] {
  const invoices = getInvoices();

  const search = searchTerm.trim().toLowerCase();

  return invoices.filter((invoice) => {
    const matchesSearch =
      !search ||
      invoice.invoiceNumber.toLowerCase().includes(search) ||
      invoice.clientName.toLowerCase().includes(search) ||
      invoice.items.some((item) =>
        item.serviceName.toLowerCase().includes(search),
      );

    const matchesStatus = status === "All" || invoice.status === status;

    return matchesSearch && matchesStatus;
  });
}

/* =========================================================
   SORT INVOICES
========================================================= */

export function getInvoicesSorted(): Invoice[] {
  return [...getInvoices()].sort(
    (a, b) =>
      new Date(b.invoiceDate).getTime() - new Date(a.invoiceDate).getTime(),
  );
}

/* =========================================================
   INVOICE SUMMARY
========================================================= */

export interface InvoiceSummary {
  total: number;
  draft: number;
  sent: number;

  /*
   * Kept for backward compatibility.
   *
   * Existing UI may still use this field.
   * It currently represents Paid invoices.
   */
  accepted: number;

  totalValue: number;
  totalPaid: number;
  outstanding: number;
}

export function getInvoiceSummary(): InvoiceSummary {
  const invoices = getInvoices();

  const activeInvoices = invoices.filter(
    (invoice) => invoice.status !== "Cancelled",
  );

  /*
   * Total includes historical/cancelled invoices
   * for compatibility with the existing summary behavior.
   */
  const total = invoices.length;

  const draft = activeInvoices.filter(
    (invoice) => invoice.status === "Draft",
  ).length;

  const sent = activeInvoices.filter(
    (invoice) => invoice.status === "Sent",
  ).length;

  /*
   * Existing API field "accepted" is preserved.
   *
   * Invoice statuses do not have "Accepted".
   * Therefore this currently counts Paid invoices.
   */
  const accepted = activeInvoices.filter(
    (invoice) => invoice.status === "Paid",
  ).length;

  const totalValue = roundMoney(
    activeInvoices.reduce(
      (sum, invoice) => sum + Number(invoice.grandTotal || 0),
      0,
    ),
  );

  const totalPaid = roundMoney(
    activeInvoices.reduce(
      (sum, invoice) =>
        sum +
        (Array.isArray(invoice.payments)
          ? invoice.payments
              .filter((payment) => payment.status !== "Cancelled")
              .reduce(
                (paymentTotal, payment) =>
                  paymentTotal + Number(payment.amountPaid || 0),
                0,
              )
          : 0),
      0,
    ),
  );

  const outstanding = Math.max(0, roundMoney(totalValue - totalPaid));

  return {
    total,

    draft,

    sent,

    accepted,

    totalValue,

    totalPaid,

    outstanding,
  };
}

/* =========================================================
   UPDATE OVERDUE INVOICES
========================================================= */

export function updateOverdueInvoices(): void {
  const invoices = getInvoices();

  const today = new Date();

  today.setHours(0, 0, 0, 0);

  let changed = false;

  invoices.forEach((invoice) => {
    /*
     * Paid and cancelled invoices are never marked overdue.
     */
    if (invoice.status === "Paid" || invoice.status === "Cancelled") {
      return;
    }

    if (!invoice.dueDate) {
      return;
    }

    const dueDate = new Date(invoice.dueDate);

    dueDate.setHours(0, 0, 0, 0);

    if (dueDate < today) {
      const paymentSummary = getInvoicePaymentSummary(invoice);

      if (!paymentSummary.isPaid) {
        if (invoice.status !== "Overdue") {
          invoice.status = "Overdue";

          invoice.updatedAt = new Date().toISOString();

          changed = true;
        }
      }
    }
  });

  if (changed) {
    saveInvoices(invoices);
  }
}

/* =========================================================
   CLEAR / ARCHIVE ALL INVOICES
========================================================= */

/*
 * IMPORTANT:
 *
 * The old implementation:
 *
 * localStorage.removeItem(STORAGE_KEY)
 *
 * permanently destroyed all invoice history.
 *
 * Bharatrath CRM should retain financial history.
 *
 * Therefore this function is retained only for backward
 * compatibility, but it now CANCELS/ARCHIVES all invoices
 * instead of permanently deleting them.
 *
 * Existing invoice IDs, numbers, payments and history remain.
 */

export function clearAllInvoices(): void {
  const invoices = getInvoices();

  if (invoices.length === 0) {
    return;
  }

  const now = new Date().toISOString();

  let changed = false;

  const archivedInvoices = invoices.map((invoice) => {
    if (invoice.status === "Cancelled") {
      return invoice;
    }

    changed = true;

    return {
      ...invoice,

      status: "Cancelled" as InvoiceStatus,

      updatedAt: now,
    };
  });

  if (changed) {
    saveInvoices(archivedInvoices);
  }
}
