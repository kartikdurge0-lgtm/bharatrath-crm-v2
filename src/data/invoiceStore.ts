/* =========================================================
   GET INVOICE BY QUOTATION ID
========================================================= */

export function getInvoiceByQuotationId(
  quotationId: string,
): Invoice | undefined {
  const normalizedQuotationId = String(quotationId || "").trim();

  if (!normalizedQuotationId) {
    return undefined;
  }

  const invoices = getInvoices();

  return invoices.find(
    (invoice) =>
      String(invoice.quotationId || "").trim() === normalizedQuotationId,
  );
}

/* =========================================================
   GET INVOICE BY QUOTATION NUMBER
========================================================= */

export function getInvoiceByQuotationNumber(
  quotationNumber: string,
): Invoice | undefined {
  const normalizedQuotationNumber = String(quotationNumber || "").trim();

  if (!normalizedQuotationNumber) {
    return undefined;
  }

  const invoices = getInvoices();

  return invoices.find(
    (invoice) =>
      String(invoice.quotationNumber || "").trim() ===
      normalizedQuotationNumber,
  );
}

/* =========================================================
   GET INVOICE BY QUOTATION REFERENCE
========================================================= */

export function getInvoiceByQuotationReference(
  quotationId?: string,
  quotationNumber?: string,
): Invoice | undefined {
  if (quotationId) {
    const invoiceById = getInvoiceByQuotationId(quotationId);

    if (invoiceById) {
      return invoiceById;
    }
  }

  if (quotationNumber) {
    const invoiceByNumber = getInvoiceByQuotationNumber(quotationNumber);

    if (invoiceByNumber) {
      return invoiceByNumber;
    }
  }

  return undefined;
}

/* =========================================================
   GENERATE INTERNAL INVOICE ID
========================================================= */

export function generateInvoiceId(): string {
  const invoices = getInvoices();

  let highest = 0;

  invoices.forEach((invoice) => {
    const match = String(invoice.id).match(/^INV-(\d+)$/);

    if (!match) {
      return;
    }

    const number = Number(match[1]);

    if (number > highest) {
      highest = number;
    }
  });

  return `INV-${String(highest + 1).padStart(3, "0")}`;
}

/* =========================================================
   CALCULATE ITEM
========================================================= */

export function calculateItem(item: Partial<InvoiceItem>): InvoiceItem {
  const basicCost = Math.max(0, Number(item.basicCost) || 0);

  const discount = Math.min(basicCost, Math.max(0, Number(item.discount) || 0));

  const finalCost = Math.max(0, basicCost - discount);

  return {
    id: item.id || generateId("ITEM"),

    serviceId: item.serviceId,

    serviceName: item.serviceName || item.description || "",

    description: item.description || item.serviceName || "",

    sac: item.sac || "",

    basicCost: roundMoney(basicCost),

    discount: roundMoney(discount),

    finalCost: roundMoney(finalCost),

    frequency: item.frequency || "",
  };
}

/* =========================================================
   CALCULATE TOTALS
========================================================= */

export interface InvoiceTotals {
  subtotal: number;
  tax: number;
  taxAmount: number;
  grandTotal: number;
}

export function calculateInvoiceTotals(
  items: InvoiceItem[],
  taxPercent: number,
): InvoiceTotals {
  const subtotal = roundMoney(
    items.reduce(
      (total: number, item: InvoiceItem) =>
        total + (Number(item.finalCost) || 0),
      0,
    ),
  );

  const tax = Math.max(0, Number(taxPercent) || 0);

  const taxAmount = roundMoney((subtotal * tax) / 100);

  const grandTotal = roundMoney(subtotal + taxAmount);

  return {
    subtotal,
    tax,
    taxAmount,
    grandTotal,
  };
}

/* =========================================================
   CREATE INVOICE
========================================================= */

/*
 * IMPORTANT:
 *
 * createInvoice() is the single source of truth
 * for invoice number generation.
 *
 * Caller-provided invoiceNumber is intentionally ignored.
 *
 * This prevents UI components from accidentally creating
 * duplicate or incorrectly prefixed invoice numbers.
 */

export function createInvoice(input: CreateInvoiceInput): Invoice {
  /*
   * A quotation can generate only ONE invoice.
   *
   * Check both quotationId and quotationNumber so that
   * old/legacy invoice records are also protected.
   *
   * Cancelled invoices are intentionally included.
   */
  const existingQuotationInvoice = getInvoiceByQuotationReference(
    input.quotationId,
    input.quotationNumber,
  );

  if (existingQuotationInvoice) {
    throw new Error(
      `An invoice already exists for quotation "${existingQuotationInvoice.quotationNumber || input.quotationNumber || input.quotationId}".`,
    );
  }

  const now = new Date().toISOString();

  const items = input.items
    .map((item) => calculateItem(item))
    .filter((item) => item.serviceName.trim() !== "");

  const totals = calculateInvoiceTotals(items, input.tax ?? 18);

  const prefix = getInvoicePrefix(input);

  const invoiceNumber = generateInvoiceNumber(
    input.clientId,
    prefix,
    input.invoiceDate,
  );

  const invoice: Invoice = {
    id: generateInvoiceId(),

    invoiceNumber,

    clientId: input.clientId,

    clientName: input.clientName,

    clientContactPerson: input.clientContactPerson,

    clientAddress: input.clientAddress,

    clientGstNumber: input.clientGstNumber,

    clientEmail: input.clientEmail,

    clientPhone: input.clientPhone,

    quotationId: input.quotationId || undefined,

    quotationNumber: input.quotationNumber || undefined,

    renewalId: input.renewalId || undefined,

    renewalReference: input.renewalReference || undefined,

    invoiceDate: input.invoiceDate,

    dueDate: input.dueDate || undefined,

    status: input.status || "Draft",

    items,

    subtotal: totals.subtotal,

    tax: totals.tax,

    taxAmount: totals.taxAmount,

    grandTotal: totals.grandTotal,

    /*
     * Existing CRM compatibility.
     */
    amount: totals.subtotal,

    notes: input.notes || "",

    payments: [],

    createdAt: now,

    updatedAt: now,
  };

  const invoices = getInvoices();

  invoices.push(invoice);

  saveInvoices(invoices);

  /* =======================================================
     ACTIVITY: INVOICE CREATED
  ======================================================= */

  void createActivityLog({
    action: "INVOICE_CREATED",

    module: "Invoices",

    record_id: invoice.id,

    record_name: invoiceRecordName(invoice),

    description: `Created invoice "${invoice.invoiceNumber}" for "${invoice.clientName}"`,

    new_data: invoice as unknown as Record<string, unknown>,
  });

  return invoice;
}

