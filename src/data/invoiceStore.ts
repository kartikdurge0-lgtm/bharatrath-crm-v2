/* =========================================================
   UPDATE INVOICE
========================================================= */

export function updateInvoice(
  invoiceId: string,
  updates: Partial<Invoice>,
): Invoice | undefined {
  const invoices = getInvoices();

  const index = invoices.findIndex((invoice) => invoice.id === invoiceId);

  if (index === -1) {
    return undefined;
  }

  const existing = invoices[index];

  /*
   * Cancelled invoices are historical records.
   *
   * They cannot be restored or changed through the
   * normal update flow.
   */
  if (existing.status === "Cancelled" && updates.status !== "Cancelled") {
    return existing;
  }

  /*
   * Invoice number is immutable.
   *
   * Even if a UI accidentally sends invoiceNumber,
   * the original number remains unchanged.
   */
  const {
    invoiceNumber: _ignoredInvoiceNumber,
    id: _ignoredId,
    createdAt: _ignoredCreatedAt,
    ...safeUpdates
  } = updates;

  void _ignoredInvoiceNumber;
  void _ignoredId;
  void _ignoredCreatedAt;

  const updatedBase: Invoice = {
    ...existing,

    ...safeUpdates,

    id: existing.id,

    invoiceNumber: existing.invoiceNumber,

    createdAt: existing.createdAt,

    updatedAt: new Date().toISOString(),
  };

  let updated: Invoice = updatedBase;

  /* =======================================================
     RECALCULATE FINANCIAL TOTALS
  ======================================================= */

  if (updates.items !== undefined || updates.tax !== undefined) {
    const sourceItems = updates.items ?? existing.items;

    const items = sourceItems.map((item) => calculateItem(item));

    const tax = updates.tax ?? existing.tax;

    const totals = calculateInvoiceTotals(items, tax);

    updated = {
      ...updatedBase,

      items,

      subtotal: totals.subtotal,

      tax: totals.tax,

      taxAmount: totals.taxAmount,

      grandTotal: totals.grandTotal,

      amount: totals.subtotal,
    };
  }

  invoices[index] = updated;

  saveInvoices(invoices);

  const oldData = existing as unknown as Record<string, unknown>;

  const newData = updated as unknown as Record<string, unknown>;

  /* =======================================================
     ACTIVITY: STATUS CHANGED
  ======================================================= */

  if (existing.status !== updated.status) {
    void createActivityLog({
      action: "STATUS_CHANGED",

      module: "Invoices",

      record_id: updated.id,

      record_name: invoiceRecordName(updated),

      description: `Changed invoice "${updated.invoiceNumber}" status from "${existing.status}" to "${updated.status}"`,

      old_data: oldData,

      new_data: newData,
    });
  }

  /* =======================================================
     ACTIVITY: GENERAL UPDATE
  ======================================================= */

  const updateKeys = Object.keys(safeUpdates).filter((key) => key !== "status");

  if (updateKeys.length > 0) {
    void createActivityLog({
      action: "UPDATE",

      module: "Invoices",

      record_id: updated.id,

      record_name: invoiceRecordName(updated),

      description: `Updated invoice "${updated.invoiceNumber}"`,

      old_data: oldData,

      new_data: newData,
    });
  }

  return updated;
}

/* =========================================================
   DELETE / ARCHIVE INVOICE
========================================================= */

/*
 * IMPORTANT:
 *
 * Invoice is NEVER physically deleted.
 *
 * deleteInvoice() changes status to Cancelled and
 * preserves the complete record.
 */

export function deleteInvoice(invoiceId: string): boolean {
  const invoices = getInvoices();

  const index = invoices.findIndex((invoice) => invoice.id === invoiceId);

  if (index === -1) {
    return false;
  }

  const invoice = invoices[index];

  if (invoice.status === "Cancelled") {
    return true;
  }

  const updatedInvoice: Invoice = {
    ...invoice,

    status: "Cancelled",

    updatedAt: new Date().toISOString(),
  };

  invoices[index] = updatedInvoice;

  saveInvoices(invoices);

  /* =======================================================
     ACTIVITY: INVOICE ARCHIVED/CANCELLED
  ======================================================= */

  void createActivityLog({
    action: "ARCHIVE",

    module: "Invoices",

    record_id: updatedInvoice.id,

    record_name: invoiceRecordName(updatedInvoice),

    description: `Cancelled invoice "${updatedInvoice.invoiceNumber}"`,

    old_data: invoice as unknown as Record<string, unknown>,

    new_data: updatedInvoice as unknown as Record<string, unknown>,
  });

  return true;
}

/* =========================================================
   DUPLICATE INVOICE
========================================================= */

/*
 * Duplicate always creates a NEW invoice.
 *
 * Therefore:
 *
 * - New internal ID
 * - New invoice number
 * - Draft status
 *
 * Original invoice remains untouched.
 */

export function duplicateInvoice(invoiceId: string): Invoice | undefined {
  const invoice = getInvoiceById(invoiceId);

  if (!invoice) {
    return undefined;
  }

  return createInvoice({
    clientId: invoice.clientId,

    clientName: invoice.clientName,

    clientContactPerson: invoice.clientContactPerson,

    clientAddress: invoice.clientAddress,

    clientGstNumber: invoice.clientGstNumber,

    clientEmail: invoice.clientEmail,

    clientPhone: invoice.clientPhone,

    /*
     * A duplicated invoice is a new independent invoice.
     * Do not carry the original quotation reference,
     * otherwise the one-invoice-per-quotation protection
     * would correctly reject the duplicate.
     */
    quotationId: undefined,

    quotationNumber: undefined,

    renewalId: undefined,

    renewalReference: undefined,

    invoiceDate: new Date().toISOString().split("T")[0],

    dueDate: invoice.dueDate,

    status: "Draft",

    items: invoice.items.map((item) => ({
      ...item,
      id: undefined,
    })),

    tax: invoice.tax,

    notes: invoice.notes,
  });
}

/* =========================================================
   ADD PAYMENT
========================================================= */

export function addInvoicePayment(
  invoiceId: string,
  input: AddPaymentInput,
): Invoice | undefined {
  const invoices = getInvoices();

  const index = invoices.findIndex((invoice) => invoice.id === invoiceId);

  if (index === -1) {
    return undefined;
  }

  const invoice = invoices[index];

  if (invoice.status === "Cancelled") {
    throw new Error("Payment cannot be added to a cancelled invoice.");
  }

  const paymentAmount = roundMoney(Number(input.amountPaid) || 0);

  if (paymentAmount <= 0) {
    throw new Error("Payment amount must be greater than zero.");
  }

  if (
    !input.paymentDate ||
    Number.isNaN(new Date(`${input.paymentDate}T00:00:00`).getTime())
  ) {
    throw new Error("Payment date is required and must be valid.");
  }

  if (!input.paymentMode?.trim()) {
    throw new Error("Payment mode is required.");
  }

  const payments = Array.isArray(invoice.payments) ? invoice.payments : [];

  const totalPaid = roundMoney(
    payments
      .filter((payment) => payment.status !== "Cancelled")
      .reduce((total, payment) => total + Number(payment.amountPaid || 0), 0),
  );

  const grandTotal = roundMoney(Number(invoice.grandTotal) || 0);

  if (grandTotal <= 0) {
    throw new Error("Invoice total must be greater than zero.");
  }

  const balance = roundMoney(grandTotal - totalPaid);

  if (balance <= 0) {
    throw new Error("This invoice is already fully paid.");
  }

  if (paymentAmount > balance) {
    throw new Error("Payment cannot be greater than outstanding balance.");
  }

  const payment: InvoicePayment = {
    id: generateId("PAY"),

    invoiceId,

    paymentDate: input.paymentDate,

    amountPaid: paymentAmount,

    paymentMode: input.paymentMode,

    transactionNumber: input.transactionNumber || "",

    paymentProof: input.paymentProof || "",

    notes: input.notes || "",

    status: "Active",
  };

  invoice.payments = [...payments, payment];

  const newTotalPaid = roundMoney(
    invoice.payments
      .filter((item) => item.status !== "Cancelled")
      .reduce((total, item) => total + Number(item.amountPaid || 0), 0),
  );

  /* =======================================================
     UPDATE INVOICE STATUS
  ======================================================= */

  if (newTotalPaid >= invoice.grandTotal) {
    invoice.status = "Paid";
  } else if (newTotalPaid > 0) {
    invoice.status = "Partially Paid";
  } else {
    invoice.status =
      invoice.dueDate && new Date(invoice.dueDate) < new Date()
        ? "Overdue"
        : "Sent";
  }

  invoice.updatedAt = new Date().toISOString();

  invoices[index] = invoice;

  saveInvoices(invoices);

  /* =======================================================
     ACTIVITY: PAYMENT ADDED
  ======================================================= */

  void createActivityLog({
    action: "PAYMENT_ADDED",

    module: "Payments",

    record_id: invoice.invoiceNumber,

    record_name: invoice.clientName,

    description: `Added payment of ₹${paymentAmount.toLocaleString(
      "en-IN",
    )} to invoice ${invoice.invoiceNumber}`,

    new_data: {
      paymentId: payment.id,

      invoiceId: invoice.id,

      invoiceNumber: invoice.invoiceNumber,

      clientName: invoice.clientName,

      amountPaid: paymentAmount,

      paymentMode: payment.paymentMode,

      paymentDate: payment.paymentDate,

      transactionNumber: payment.transactionNumber || "",

      totalPaid: newTotalPaid,

      outstandingBalance: Math.max(
        0,
        roundMoney(invoice.grandTotal - newTotalPaid),
      ),

      invoiceStatus: invoice.status,
    },
  });

  return invoice;
}

/* =========================================================
   CANCEL PAYMENT
   Payment remains permanently in history.
========================================================= */

export function cancelInvoicePayment(
  invoiceId: string,
  paymentId: string,
  cancellationReason: string = "Payment cancelled",
): Invoice | undefined {
  const invoices = getInvoices();

  const index = invoices.findIndex((invoice) => invoice.id === invoiceId);

  if (index === -1) {
    return undefined;
  }

  const invoice = invoices[index];

  if (!Array.isArray(invoice.payments)) {
    invoice.payments = [];
  }

  const paymentIndex = invoice.payments.findIndex(
    (payment) => payment.id === paymentId,
  );

  if (paymentIndex === -1) {
    return undefined;
  }

  const payment = invoice.payments[paymentIndex];

  if (payment.status === "Cancelled") {
    return invoice;
  }

  const reason = cancellationReason.trim() || "Payment cancelled";

  const cancelledAt = new Date().toISOString();

  invoice.payments[paymentIndex] = {
    ...payment,

    status: "Cancelled",

    cancelledAt,

    cancellationReason: reason,
  };

  /* =======================================================
     RECALCULATE ACTIVE PAYMENTS
  ======================================================= */

  const activePayments = invoice.payments.filter(
    (item) => item.status !== "Cancelled",
  );

  const totalPaid = roundMoney(
    activePayments.reduce(
      (total, item) => total + Number(item.amountPaid || 0),
      0,
    ),
  );

  /* =======================================================
     UPDATE INVOICE STATUS
  ======================================================= */

  if (totalPaid <= 0) {
    if (
      invoice.status === "Paid" ||
      invoice.status === "Partially Paid" ||
      invoice.status === "Overdue"
    ) {
      invoice.status =
        invoice.dueDate && new Date(invoice.dueDate) < new Date()
          ? "Overdue"
          : "Sent";
    }
  } else if (totalPaid >= invoice.grandTotal) {
    invoice.status = "Paid";
  } else {
    invoice.status = "Partially Paid";
  }

  invoice.updatedAt = cancelledAt;

  invoices[index] = invoice;

  saveInvoices(invoices);

  /* =======================================================
     ACTIVITY: PAYMENT CANCELLED
  ======================================================= */

  void createActivityLog({
    action: "PAYMENT_CANCELLED",

    module: "Payments",

    record_id: invoice.invoiceNumber,

    record_name: invoice.clientName,

    description: `Cancelled payment of ₹${Number(
      payment.amountPaid || 0,
    ).toLocaleString("en-IN")} for invoice ${invoice.invoiceNumber}`,

    old_data: {
      paymentId: payment.id,

      invoiceId: invoice.id,

      invoiceNumber: invoice.invoiceNumber,

      clientName: invoice.clientName,

      amountPaid: payment.amountPaid,

      paymentMode: payment.paymentMode,

      paymentDate: payment.paymentDate,

      status: "Active",
    },

    new_data: {
      paymentId: payment.id,

      status: "Cancelled",

      cancellationReason: reason,

      cancelledAt,

      totalPaid,

      outstandingBalance: Math.max(
        0,
        roundMoney(invoice.grandTotal - totalPaid),
      ),

      invoiceStatus: invoice.status,
    },
  });

  return invoice;
}

