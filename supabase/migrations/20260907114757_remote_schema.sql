CREATE OR REPLACE FUNCTION "public"."set_activity_log_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_email TEXT;
  v_name TEXT;
BEGIN
  -- Always use the actual logged-in user
  NEW.user_id := auth.uid();

  -- Get email directly from auth.users
  SELECT email
  INTO v_email
  FROM auth.users
  WHERE id = auth.uid();

  -- Try common Google/Auth profile name fields
  SELECT COALESCE(
    raw_user_meta_data->>'full_name',
    raw_user_meta_data->>'name',
    raw_user_meta_data->>'display_name'
  )
  INTO v_name
  FROM auth.users
  WHERE id = auth.uid();

  -- Store user details
  NEW.user_email := COALESCE(v_email, '');

  NEW.user_name := COALESCE(
    NULLIF(v_name, ''),
    NULLIF(v_email, ''),
    'Unknown User'
  );

  RETURN NEW;
END;
$$;


